"""Curated fact inventories for fact-discrimination coverage (FDC).

Manual research annotation, not generated. Each domain lists the model facts an
ordinary grounding request can use and the agent can observe. Every stored column
of an included entity, and every model relationship, receives a disposition.
build.py checks that accounting against the adopted models and emits catalogs.

Fact kinds (see ../criterion.md):
  A  attribute used as an identifying condition (text, identity, time, quantity, state)
  R  relationship used to connect a referent to identifying evidence
  H  hierarchy/self-relationship semantics (direct vs transitive, level)
  B  same-record binding across a to-many relationship
  D  derived representation with an ordinary use

Column exclusion categories:
  handle       storage/direct identifier; supplied-ID controls, not requirements
  fk           reference column, accounted by an R/H fact or relationship exclusion
  constant     fixed type tag
  bookkeeping  etags, sequences, hashes, ordering, caches with a canonical source
  presentation colors, icons, avatars, links
  config       policy/configuration flags without ordinary identifying use
  structured   JSON payloads without implemented identifying semantics
  unexposed    stored, but not returned by dispatched reads for this actor
  filtered     state the API filters out of listings; not discriminable by the agent
  alias        another representation of an included fact (named in the note)
  rare         observable, but not an ordinary identifying condition in this campaign
"""

